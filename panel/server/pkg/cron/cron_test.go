func TestParseMatchesSchedulerParser(t *testing.T) {
	cases := []string{
		"0 */5 * * * *",
		"0 9 * JAN MON",
		"0 0 L * *",
		"0 0 15W * *",
		"0 0 * * MON#2",
	}

	for _, expr := range cases {
		parser, _, err := parserForParts(strings.Fields(expr))
		_, parseErr := parser.Parse(expr)
		expectValid := err == nil && parseErr == nil

		result := Parse(expr)
		if result.Valid != expectValid {
			t.Fatalf("unexpected validity for %q: got %v want %v", expr, result.Valid, expectValid)
		}
	}
}

func TestNextRunTimesMatchesSchedule(t *testing.T) {
	expr := "0 */5 * * * *"
	schedule, err := parseSchedule(expr)
	if err != nil {
		t.Fatalf("parseSchedule error: %v", err)
	}

	got := NextRunTimes(expr, 3)
	if len(got) != 3 {
		t.Fatalf("expected 3 next run times, got %d", len(got))
	}

	cursor := time.Now()
	for i, next := range got {
		expected := schedule.Next(cursor)
		if !next.Equal(expected) {
			t.Fatalf("unexpected next run at index %d: got %v want %v", i, next, expected)
		}
		cursor = expected
	}
}

// TestFirstRunSecondOfDay 钉住任务列表「按定时规则排序」的排序键（issue #151）：一天之内最早一次触发的时刻。
//
// 每条用例都拿两个不同的「现在」各算一遍、结果必须相同：排序键只取决于规则本身，
// 与现在几点、今天星期几无关，否则刷新一次列表顺序就会漂移。
//
// 「00:00 本身要能命中」是这组用例的重点：实现里起点用「今天 0 点减 1 秒」，
// 因为 robfig 的 Next 会先把起点进位到下一整秒。要是直接从 0 点起找，0 点被排除在外，
// `0 0 0,12 * * *` 会被算成 12:00、`*/10 * * * * *` 会被算成 00:00:10 —— 下面专门放了这两条。
// 单写一条 `0 0 0 * * *` 钉不住它：从 0 点起找会落到明天 00:00，时刻照样是 0。
func TestFirstRunSecondOfDay(t *testing.T) {
	zone := time.FixedZone("CST", 8*3600)
	// 周三下午 2 点，和周日刚过 0 点：一个在当天所有时刻之后，一个正好压在 0 点上。
	nows := []time.Time{
		time.Date(2026, 9, 23, 14, 0, 0, 0, zone),
		time.Date(2026, 9, 27, 0, 0, 0, 0, zone),
	}

	cases := []struct {
		raw    string
		want   int
		wantOK bool
		reason string
	}{
		{"0 0 9 * * *", 9 * 3600, true, "6 段每天 09:00"},
		{"0 9 * * *", 9 * 3600, true, "5 段每天 09:00，与 6 段同一时刻"},
		{"0 */5 * * * *", 0, true, "每 5 分钟：0 点整也会跑，落在 00:00"},
		{"*/10 * * * * *", 0, true, "秒级：00:00:00 必须命中，不能算成 00:00:10"},
		{"0 0 0,12 * * *", 0, true, "0 点与 12 点：00:00 必须命中，不能算成 12:00"},
		{"0 0 0 * * *", 0, true, "每天 00:00"},
		{"0 0 8,20 * * *", 8 * 3600, true, "一天两个时刻取最早"},
		{"0 0 9 * * 1", 9 * 3600, true, "每周一 09:00，与每天 09:00 同一时刻"},
		{"0 */10 9-22 * * *", 9 * 3600, true, "9-22 点每 10 分钟：落在时段起点"},
		{"10 50 9 * * *", 9*3600 + 50*60 + 10, true, "非零固定秒（随机弹层产物）要算进去"},
		{"0 0 20 * * *\n0 0 8 * * 1", 8 * 3600, true, "多行取最小，哪怕最早那行是每周一次"},
		{"0 30 6 1 * *", 6*3600 + 30*60, true, "每月 1 日 06:30"},
		{"0 0 0 30 2 *", 0, false, "2 月 30 日永不触发"},
		{"", 0, false, "空串（手动 / 开机任务）"},
		{"bad cron", 0, false, "表达式非法"},
	}

	for _, item := range cases {
		for _, now := range nows {
			got, ok := FirstRunSecondOfDay(item.raw, now)
			if ok != item.wantOK || got != item.want {
				t.Fatalf("规则 %q（%s）在 %s 算出 (%d, %v)，期望 (%d, %v)",
					item.raw, item.reason, now.Format("2006-01-02 15:04:05 Mon"), got, ok, item.want, item.wantOK)
			}
		}
	}
}

// TestParseInvalidFieldCount 除了「段数不合法要被拒绝」，还要钉住那条中文错误文案。
//
// errInvalidFieldCount 是段数不合法时唯一的报错出口，会原样渲染成面板上的红色错误徽标。
// 只说一句英文的 "cron expression must have 5 or 6 fields"，用户既不知道 5 段和 6 段
// 分别怎么排，也不知道自己抄来的 @daily / @every 1h 为什么不认。所以这里必须钉住两层含义：
//  1. 合法段数是 5 段或 6 段；
//  2. @daily 这类简写【不支持】（它们段数对不上，根本进不到解析器）。
//
// 刻意只断言几个关键片段、不断言整句：这条文案要迁就徽标宽度，以后调标点、补例子都很正常，
// 整句断言会让每次措辞微调都无谓地变红，最后大家干脆把断言删了。
func TestParseInvalidFieldCount(t *testing.T) {
	// 少一段、多一段、以及用户最容易照着别处教程抄来的两种简写。
	for _, expr := range []string{"* * * *", "* * * * * * *", "@daily", "@every 1h"} {
		result := Parse(expr)
		if result.Valid {
			t.Fatalf("表达式 %q 段数不合法，应当被拒绝", expr)
		}
		for _, fragment := range []string{"5 段或 6 段", "不支持", "@daily"} {
			if !strings.Contains(result.Error, fragment) {
				t.Fatalf("表达式 %q 的错误文案缺少关键片段 %q（不能退回英文/只说一句「段数错误」）：got %q",
					expr, fragment, result.Error)
			}
		}
	}
}

// TestDescribeDailyHoursAndSeconds 锁住 describe() 里几条容易出「自信的错误」的分支：
// 逗号小时列表、非零固定秒（随机弹层「合并一条 / 随机到秒」的常态产物）、
// 「时段 + 星期」（`0 */10 9-22 * * 1-5` 这类），以及三条 `*/N` 早退分支的守卫。
//
// 早退守卫是本组用例的重点：`*/N` 分支以前只看自己那一段，`*/10 9-22 * * 1-5` 会被说成
// 「每10分钟」，把「9-22 点」和「工作日」整段吃掉。表达式本来就能存能跑，用户看到这句
// 却会以为面板不支持时段和星期 —— 兜底文案只是含糊，这种是错的，比含糊更坏。
//
// 与之对称的是 secondFixed 守卫：秒是 `*` 或 `*/N` 时，「每分钟 / 每小时 / HH:MM / 每月X日」
// 这些说法全都不成立（`*/10 0 9 * * *` 每天跑 6 次，不是「每天 09:00」），必须整条落兜底。
// 下面成对写了「该落兜底」与「不该被守卫误伤」两类用例，守宽守窄都会红。
func TestDescribeDailyHoursAndSeconds(t *testing.T) {
	cases := []struct {
		expression string
		want       string
		reason     string
	}{
		// 逗号小时列表：随机弹层「合并一条」形态
		{"10 50 9,21 * * *", "每天 09:50:10、21:50:10", "逗号小时 + 非零固定秒"},
		{"0 0 9,12,18 * * *", "每天 09:00、12:00、18:00", "逗号小时 + 零秒不补秒位"},
		{"0 30 9,21 * * 1-5", "工作日 09:30、21:30", "逗号小时 + 工作日，星期前缀要带上"},
		// 单个小时：走既有的「每天 HH:MM」分支，秒位由 dailySecondSuffix 决定补不补
		{"10 50 9 * * *", "每天 09:50:10", "非零固定秒要显示出来"},
		{"0 50 9 * * *", "每天 09:50", "零秒不补，与 5 段的 50 9 * * * 保持一致"},
		{"30 0 0 * * *", "每天 00:00:30", "「每天 00:00」分支也要能带秒位"},
		// 星期前缀接进「每天 00:00」「每天 HH:MM」两条分支
		{"0 0 9 * * 1-5", "工作日 09:00", "出厂预设「工作日9点」不能再说成「每天」"},
		{"0 9 * * 1-5", "工作日 09:00", "同上，5 段写法"},
		{"0 0 18 * * 1-5", "工作日 18:00", "出厂预设「工作日18点」"},
		{"0 0 10 * * 0,6", "周末 10:00", "出厂预设「周末10点」"},
		{"0 10 * * 6,0", "周末 10:00", "周末两天顺序不限"},
		{"0 0 0 * * 1", "每周一 00:00", "出厂预设「每周一0点」，00:00 分支也要带星期"},
		{"0 0 * * 1", "每周一 00:00", "同上，5 段写法"},
		{"0 0 12 * * 1,3", "每周一、每周三 12:00", "纯数字逗号列表逐个翻出来"},
		{"0 0 9 * * *", "每天 09:00", "星期不限定时保持原样"},
		// 时段 + 星期：本轮新增的两条描述形态，6 段与 5 段写法都要认
		{"0 */10 9-22 * * 1-5", "工作日 9-22 点，每 10 分钟", "小时区间 + 工作日 + 分钟步进"},
		{"*/10 9-22 * * 1-5", "工作日 9-22 点，每 10 分钟", "同上，5 段写法"},
		{"0 */10 9-22 * * *", "每天 9-22 点，每 10 分钟", "守卫生效后不能再输出「每10分钟」"},
		{"*/10 9-22 * * *", "每天 9-22 点，每 10 分钟", "同上，5 段写法"},
		{"0 */10 9-22 * * 0,6", "周末 9-22 点，每 10 分钟", "小时区间 + 周末"},
		{"0 */30 9-18 * * 1-5", "工作日 9-18 点，每 30 分钟", "出厂预设「工作日9-18点每30分钟」"},
		{"*/30 9-18 * * 1,2,3,4,5", "工作日 9-18 点，每 30 分钟", "工作日的逗号写法也要认"},
		{"0 */10 9 * * 1-5", "工作日 9 点，每 10 分钟", "单个小时 + 分钟步进"},
		{"*/10 9 * * 1-5", "工作日 9 点，每 10 分钟", "同上，5 段写法"},
		{"0 0 9-22 * * 1-5", "工作日 9-22 点整点", "小时区间 + 分钟固定为 0"},
		{"0 9-22 * * 1-5", "工作日 9-22 点整点", "同上，5 段写法"},
		{"0 30 9-22 * * *", "每天 9-22 点，每小时第 30 分钟", "小时区间 + 分钟固定非 0"},
		{"30 9-22 * * *", "每天 9-22 点，每小时第 30 分钟", "同上，5 段写法"},
		// 「每小时整点 / 每小时第 N 分钟」：小时段是裸 `*` 时以前没有分支接手，一路落兜底，
		// 出厂预设「每小时」在预设面板写着人话、选中后徽标却退化成兜底文案。
		{"0 0 * * * *", "每小时整点", "出厂预设「每小时」不该再落兜底"},
		{"0 30 * * * *", "每小时第 30 分钟", "分钟非 0 时说清是第几分钟"},
		{"0 0 * * * 1-5", "工作日 每小时整点", "每小时分支也要带星期前缀"},
		{"0 * * * *", "每小时整点", "同上，5 段写法"},
		{"*/10 30 * * * *", "自定义 cron 表达式", "秒是 */N，那一分钟里跑 6 次，不能说成「每小时第 30 分钟」"},
		// 早退守卫的反例：不许再把其它段吃掉
		{"0 30 */2 * * *", "自定义 cron 表达式", "分钟不是 0，不能再说成「每2小时」"},
		{"* */10 9-22 * * 1-5", "自定义 cron 表达式", "秒是 *，「每 10 分钟」这句话不成立"},
		// 秒段守卫：秒是 `*` / `*/N` 时，下面这些「确定时刻 / 分钟级频率」的说法全都不成立。
		// 这类表达式在秒级上高频触发，说成确定时刻是【自信的错误】，比兜底文案更坏。
		// 反向的「不该被守卫误伤」由下面既有的 `*/10 * * * * *` → 「每10秒」把守（其余段全不限定时
		// 仍然要走秒步进早退），守宽守窄都会红。
		{"*/2 0 10 * * *", "自定义 cron 表达式", "秒是 */N，不能说成确定时刻"},
		{"*/10 * * * * 1-5", "自定义 cron 表达式", "秒是 */N 且限定星期，不能说成「每分钟」"},
		{"*/10 */5 * * * *", "自定义 cron 表达式", "秒是 */N，「每5分钟」这句话不成立"},
		{"*/10 0 0 1 * *", "自定义 cron 表达式", "秒是 */N，不能说成「每月 1日 00:00」"},
		{"*/10 0 9,21 * * *", "自定义 cron 表达式", "秒是 */N，不能说成确定时刻列表"},
		{"* 0 9 * * *", "自定义 cron 表达式", "秒是 *，那一分钟里每秒都跑，不能说成「每天 09:00」"},
		{"0-30 0 9 * * *", "自定义 cron 表达式", "秒是区间，同样不能说成确定时刻"},
		{"* * * * * *", "自定义 cron 表达式", "每秒执行，不能说成每分钟"},
		// 「每分钟」分支的星期前缀
		{"0 * * * * 1-5", "工作日 每分钟", "每分钟分支也要带星期前缀"},
		{"0 * * * * MON", "自定义 cron 表达式", "星期认不出，整条落兜底"},
		// `?` 与 `*` 同义（Quartz 惯用写法把日写成 `?`、交给星期段说了算）。
		// 尾部「每年 / 每月」两条分支以前判的是 `!= "*"`，`?` 会判真，于是星期认不出时
		// 控制流落到那里，把 `?` 原样吐进中文（「每月 ?日 09:00」），还顺手把星期限定吃掉。
		// 同义的 `0 0 9 * * MON-FRI` 一直正确落兜底，两者必须说法一致。
		{"0 0 9 ? * MON-FRI", "自定义 cron 表达式", "day 用 ? 且星期认不出，不能掉进每月分支"},
		{"0 9 ? * MON-FRI", "自定义 cron 表达式", "同上，5 段写法"},
		{"0 0 0 ? ? MON", "自定义 cron 表达式", "day/month 都是 ? 时不能掉进每年分支"},
		{"30 0 0 ? * MON", "自定义 cron 表达式", "非零固定秒也一样，不能吞掉秒位说成「每月 ?日 00:00」"},
		// 正向锚点：`?` 的正常路径不能被弄坏，守宽守窄都会红
		{"0 0 9 ? * *", "每天 09:00", "day 用 ? 就是「不限定」，与 * 同义"},
		{"0 0 9 1 ? *", "每月 1日 09:00", "month 用 ? 是「每月」，不能升格成「每年」"},
		// 不该猜的：宁可落兜底也不给出自信的错误描述
		{"0 0 9-11,21 * * *", "自定义 cron 表达式", "小时段含区间，numericHourList 刻意不展开"},
		{"0 */10 9-22/2 * * 1-5", "自定义 cron 表达式", "带步进的小时区间，hourRangeText 不认"},
		{"0 0 12 * * MON", "自定义 cron 表达式", "星期用英文缩写，weekdayPrefix 认不出就整条落兜底"},
		{"0 0 12 * * 1-5/2", "自定义 cron 表达式", "带步进的星期区间，同样认不出"},
		// 既有行为不能被新分支截胡
		{"0 */5 * * * *", "每5分钟", "其余段都不限定，仍然走 describeSimpleStep 早退"},
		{"*/10 * * * * *", "每10秒", "秒步进早退"},
		{"0 0 */2 * * *", "每2小时", "分秒都是 0，仍然是干净的「每2小时」"},
		{"0 * * * * *", "每分钟", "每分钟分支"},
		{"0 0 * * *", "每天 00:00", "5 段表达式没有秒位"},
	}

	for _, item := range cases {
		result := Parse(item.expression)
		if !result.Valid {
			t.Fatalf("表达式 %q 应当合法，却报错：%s", item.expression, result.Error)
		}
		if result.Description != item.want {
			t.Fatalf("表达式 %q（%s）描述不符：got %q want %q",
				item.expression, item.reason, result.Description, item.want)
		}
	}
}

// TestDescribeTemplatesSnapshot 把出厂预设的描述整体钉成快照，防止以后有人改 describe()
// 时把某条预设打回兜底文案，或者悄悄改掉别的预设的说法。
//
// 「工作日9点」「工作日18点」「周末10点」「每周一0点」以前被说成「每天 …」（那两条分支不看 dow），
// 已经修掉，快照按修好之后的说法钉；三条「时段 + 每N分钟」预设也在里面。
//
// 「每小时」`0 0 * * * *` 原本落在兜底「自定义 cron 表达式」：hour 是裸 `*` 而不是 `*/N`，
// describeSimpleStep 认不出来，后面的分支又都要求 hour 是纯数字或区间，于是预设面板写着
// 「每小时整点执行」、选中后规则行的徽标却退化成兜底文案。describe() 补上「每小时整点」分支后，
// 这条快照跟着改成了人话，其余 23 条一个字都不该动 —— 真变了就说明守卫写宽了。
func TestDescribeTemplatesSnapshot(t *testing.T) {
	snapshot := map[string]string{
		"0 * * * * *":         "每分钟",
		"0 */5 * * * *":       "每5分钟",
		"0 */10 * * * *":      "每10分钟",
		"0 */15 * * * *":      "每15分钟",
		"0 */30 * * * *":      "每30分钟",
		"0 0 * * * *":         "每小时整点",
		"0 0 */2 * * *":       "每2小时",
		"0 0 */6 * * *":       "每6小时",
		"0 0 0 * * *":         "每天 00:00",
		"0 0 6 * * *":         "每天 06:00",
		"0 0 9 * * *":         "每天 09:00",
		"0 0 12 * * *":        "每天 12:00",
		"0 0 18 * * *":        "每天 18:00",
		"0 */10 9-22 * * *":   "每天 9-22 点，每 10 分钟",
		"0 0 9 * * 1-5":       "工作日 09:00",
		"0 0 18 * * 1-5":      "工作日 18:00",
		"0 */10 9-22 * * 1-5": "工作日 9-22 点，每 10 分钟",
		"0 */30 9-18 * * 1-5": "工作日 9-18 点，每 30 分钟",
		"0 0 10 * * 0,6":      "周末 10:00",
		"0 0 0 * * 1":         "每周一 00:00",
		"0 0 0 1 * *":         "每月 1日 00:00",
		"0 0 0 15 * *":        "每月 15日 00:00",
		"*/10 * * * * *":      "每10秒",
		"*/30 * * * * *":      "每30秒",
	}

	templates := GetTemplates()
	if len(templates) != len(snapshot) {
		t.Fatalf("出厂预设数量与快照不一致：预设 %d 条、快照 %d 条，改了预设就要同步改快照",
			len(templates), len(snapshot))
	}

	for _, template := range templates {
		expression := template["expression"]
		want, ok := snapshot[expression]
		if !ok {
			t.Fatalf("预设 %q（%s）不在快照里，新增预设时请一并补进来", expression, template["name"])
		}

		result := Parse(expression)
		if !result.Valid {
			t.Fatalf("预设 %q（%s）解析失败：%s", expression, template["name"], result.Error)
		}
		if result.Description != want {
			t.Fatalf("预设 %q（%s）描述变了：got %q want %q",
				expression, template["name"], result.Description, want)
		}
	}
}
